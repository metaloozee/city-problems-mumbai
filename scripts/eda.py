"""Exploratory data analysis of the unified dataset -> data/eda/EDA.md + data/eda/*.png
Run after scripts/build_dataset.py:  python3 scripts/eda.py
"""
import gzip, json, pathlib
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "eda"; OUT.mkdir(parents=True, exist_ok=True)
INK, MUTED, GRID, HEAT, SURFACE = "#262626", "#262626a3", "#ededed", "#fa5d19", "#ffffff"

df = pd.read_csv(ROOT / "data" / "processed" / "problems.csv.gz", parse_dates=["reported_at", "closed_at"])
df["reported_at"] = pd.to_datetime(df.reported_at, utc=True).dt.tz_convert("Asia/Kolkata")
wards = pd.read_csv(ROOT / "data" / "processed" / "wards.csv")
stats = json.load(open(ROOT / "data" / "prepare_stats.json"))
raw = pd.DataFrame(json.load(gzip.open(ROOT / "data" / "raw" / "complaints_raw.json.gz")))
md: list[str] = []
def h(t): md.append(f"\n## {t}\n")
def p(t): md.append(t + "\n")
def table(d: pd.DataFrame, index=True): md.append(d.to_markdown(index=index) + "\n")

def style(ax, title):
    ax.set_title(title, loc="left", fontsize=12, color=INK, pad=12)
    for s in ("top", "right", "left"): ax.spines[s].set_visible(False)
    ax.spines["bottom"].set_color(GRID)
    ax.tick_params(colors=MUTED, labelsize=9, length=0)
    ax.grid(axis="y", color=GRID, linewidth=1); ax.set_axisbelow(True)

def save(fig, name):
    fig.savefig(OUT / name, dpi=150, bbox_inches="tight", facecolor=SURFACE); plt.close(fig)
    md.append(f"\n![{name}]({name})\n")

closed = df[df.status.isin(["Resolved", "Rejected"])]
resolved = df[df.status == "Resolved"]
open_ = df[df.is_open]

md.append("# EDA: Mumbai civic problems (BMC MARG, Mar to Oct 2026)\n")
p(f"Unified rows: **{len(df):,}** · reported {df.reported_at.min():%d %b %Y} to {df.reported_at.max():%d %b %Y} (IST) · "
  f"rows with a real map location: **{int(df.has_location.sum()):,}**. Generated by `scripts/eda.py`.")

h("1. Sources and how they were joined")
p(f"- Layer 0 (CCRS, every department and channel): {stats['raw_rows']['ccrs']:,} rows.")
p(f"- Layer 16 (Pothole QuickFix): {stats['raw_rows']['pothole_quickfix']:,} rows. {stats['pothole_rows_matching_ccrs']:,} of them have the same complaint ID as a layer 0 row, "
  f"so the layers are two views of one complaint register. The pipeline joins on ID and copies the pothole fields (road type, invalid flag, resolved date) onto the layer 0 row. "
  f"Only {stats['pothole_rows_only_in_quickfix']} pothole rows are added as new rows. {stats['pothole_rows_without_id_dropped']} pothole rows have no complaint ID and are dropped.")
p("- The old pipeline stacked both layers and then de-duplicated by ID, which silently discarded the pothole fields.")

h("2. Missing values in the raw complaint layer")
miss = (raw.isna().mean() * 100).round(1).sort_values(ascending=False).rename("% missing").to_frame()
table(miss[miss["% missing"] > 0])
p("`REOPEN` is always empty and `RESOLUTION_HRS` (layer 16) is always empty, so neither is used. Ward, zone and division are missing on ~13% of rows; "
  "almost all of those are the placeholder-location rows below.")

h("3. Location quality")
ch = df.groupby("channel").agg(rows=("id", "size"), with_location=("has_location", "mean")).sort_values("rows", ascending=False)
ch["with_location"] = (ch.with_location * 100).round(1).astype(str) + "%"
table(ch)
p(f"{stats['no_real_location']['placeholder_point']:,} rows sit on one point (19.07766, 72.87741). They are almost all from the 1916 helpline, and "
  "most are Discarded. They stay in the database with `has_location = false` and empty coordinates, but they are not drawn on the map. "
  f"{stats['no_real_location']['outside_mumbai_or_missing']} more rows have coordinates outside Greater Mumbai.")

h("4. Status: \"Closed\" does not mean \"fixed\"")
inv = pd.crosstab(raw.COMPLAINT_STATUS, raw.INVALID.fillna("(empty)"))
table(inv)
st = df.status.value_counts().rename("rows").to_frame(); st["share"] = (st.rows / len(df) * 100).round(1).astype(str) + "%"
table(st)
p(f"BMC marks **{int((df.status == 'Rejected').sum()):,}** complaints as CLOSED while also flagging them INVALID. The earlier app counted those as resolved, "
  f"which overstated the fix rate. The unified status splits them: **Resolved** (closed and valid) and **Rejected** (closed as invalid). "
  f"Of complaints that BMC closed, {len(resolved) / len(closed) * 100:.1f}% were resolved and {(1 - len(resolved) / len(closed)) * 100:.1f}% were rejected.")

h("5. What people complain about")
cat = df.groupby("category").agg(rows=("id", "size"), open_now=("is_open", "sum"),
                                 rejected_pct=("status", lambda s: round((s == "Rejected").mean() * 100, 1))).sort_values("rows", ascending=False)
table(cat)
fig, ax = plt.subplots(figsize=(8, 4.6))
c2 = cat.rows.sort_values()
ax.barh(c2.index, c2.values, color=HEAT, height=0.6)
for y, v in enumerate(c2.values): ax.text(v + 150, y, f"{v:,}", va="center", fontsize=8, color=MUTED)
style(ax, "Complaints by category"); ax.grid(axis="x", color=GRID); ax.grid(axis="y", visible=False)
save(fig, "category.png")
p("Category is derived from the complaint name the citizen picked, with BMC's department as a fallback, because the same complaint name is often routed "
  "to different departments (for example \"Garbage / silt / tree branches not lifted\" appears under Solid Waste, Garden and Maintenance).")

h("6. When problems are reported")
monthly = df.set_index("reported_at").groupby([pd.Grouper(freq="MS"), "category"]).size().unstack(fill_value=0)
monthly.index = monthly.index.strftime("%Y-%m")
table(monthly[["Potholes", "Drains & Sewage", "Garbage & Cleanliness", "Water Supply"]])
p("Potholes and drains rise sharply with the monsoon (June to September). March and October are partial months.")
fig, ax = plt.subplots(figsize=(8, 3.6))
hours = df.reported_at.dt.hour.value_counts().sort_index()
ax.bar(hours.index, hours.values, color=HEAT, width=0.7)
style(ax, "Complaints by hour of day (IST)"); ax.set_xticks(range(0, 24, 3))
save(fig, "hour.png")
p(f"Peak hour in IST is {hours.idxmax()}:00. The raw timestamps are UTC; the old app used UTC dates, which put late-evening complaints on the wrong day.")

h("7. How long fixes take")
d = resolved.groupby("category").days_to_close.describe(percentiles=[0.5, 0.9])[["count", "50%", "90%", "mean"]].round(1)
d.columns = ["resolved", "median days", "90th pct days", "mean days"]
table(d.sort_values("median days", ascending=False))
fig, ax = plt.subplots(figsize=(8, 3.6))
ax.hist(resolved.days_to_close.dropna().clip(upper=120), bins=60, color=HEAT)
style(ax, "Days from report to fix (resolved complaints, capped at 120)")
save(fig, "days_to_close.png")
p(f"The distribution is very skewed: median {resolved.days_to_close.median():.1f} days, mean {resolved.days_to_close.mean():.1f} days. "
  "The app shows medians for that reason. Closure time is the date of BMC's \"after\" photo, which is the best closure signal the service publishes.")

h("8. Wards")
w = df[df.ward.notna()].groupby("ward").agg(rows=("id", "size"), open_now=("is_open", "sum"),
    resolved=("status", lambda s: (s == "Resolved").sum()), closed=("status", lambda s: s.isin(["Resolved", "Rejected"]).sum()))
w = w.join(wards.set_index("ward")[["name", "areas", "population"]])
w["per_100k"] = (w.rows / w.population * 1e5).round(0).astype(int)
w["fix_rate"] = (w.resolved / w.closed * 100).round(1)
w["median_days"] = resolved.groupby("ward").days_to_close.median().round(1)
w = w.sort_values("per_100k", ascending=False)
table(w[["name", "areas", "rows", "per_100k", "open_now", "fix_rate", "median_days"]])
fig, ax = plt.subplots(figsize=(8, 5.5))
w2 = w.per_100k.sort_values()
ax.barh([f"{w.loc[k, 'name']}" for k in w2.index], w2.values, color=HEAT, height=0.6)
style(ax, "Complaints per 100,000 residents, by ward"); ax.grid(axis="x", color=GRID); ax.grid(axis="y", visible=False)
save(fig, "ward_per_100k.png")
p("`fix_rate` = Resolved / (Resolved + Rejected). Population comes from BMC's ward boundary layer.")

h("9. Escalation")
e = df.groupby("category").escalated.mean().mul(100).round(1).sort_values(ascending=False).rename("% escalated").to_frame()
table(e)
p("Escalation is BMC's own flag for complaints that passed their first deadline.")

h("10. Decisions for the unified dataset")
for t in [
    "One row per complaint ID. Pothole QuickFix fields are merged onto the matching CCRS row.",
    "Times are stored as timestamps with the IST offset (`reported_at`, `closed_at`).",
    "Status vocabulary: Open, In Review, In Progress (all `is_open = true`), Resolved, Rejected, Discarded.",
    "`days_to_close` is filled for Resolved and Rejected rows only. Values below 0 or above 400 days are blanked.",
    "Rows with no real location are kept with `has_location = false` and null coordinates, so city totals stay complete.",
    "Ward is filled by point-in-polygon when BMC left it blank and the point is real. Zone and division are filled from the ward.",
    "Categories: 14 citizen-facing groups (see `CATEGORY_RULES` in `scripts/build_dataset.py`).",
    "Citizen reports from the app go into the same `problems` table with `source = 'citizen'`.",
]: p(f"- {t}")

(OUT / "EDA.md").write_text("".join(m if m.endswith("\n") else m + "\n" for m in md))
print("wrote", OUT / "EDA.md")
